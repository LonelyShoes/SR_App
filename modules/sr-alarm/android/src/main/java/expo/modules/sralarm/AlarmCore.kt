package expo.modules.sralarm

import android.app.AlarmManager
import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.media.AudioAttributes
import android.media.AudioManager
import android.os.Build
import android.provider.Settings
import androidx.core.app.NotificationCompat

/**
 * Timer alarm shared by the module, the receiver and the alarm screen.
 *
 * AlarmManager.setAlarmClock fires exactly even in Doze; the receiver then posts an
 * insistent notification (the alarm sound loops until dismissed) whose full-screen
 * intent shows [AlarmActivity] over the lock screen.
 */
object AlarmCore {
  const val CHANNEL_ID = "timer-alarm-ring"
  const val ACTION_FIRE = "expo.modules.sralarm.FIRE"
  const val ACTION_DISMISS = "expo.modules.sralarm.DISMISS"
  const val EXTRA_TITLE = "title"
  const val EXTRA_BODY = "body"
  private const val NOTIFICATION_ID = 7301
  private const val REQUEST_FIRE = 7301
  private const val REQUEST_SCREEN = 7302
  private const val REQUEST_DISMISS = 7303
  private const val REQUEST_SHOW = 7304

  // Stop ringing on its own if nobody answers
  private const val RING_TIMEOUT_MS = 3 * 60 * 1000L
  private val VIBRATION = longArrayOf(0, 800, 400, 800, 400, 800)

  /** Called after the alarm is dismissed from anywhere (notification, alarm screen, app). */
  val dismissListeners = mutableSetOf<() -> Unit>()

  private fun alarmManager(ctx: Context) = ctx.getSystemService(Context.ALARM_SERVICE) as AlarmManager

  private fun notificationManager(ctx: Context) =
    ctx.getSystemService(Context.NOTIFICATION_SERVICE) as NotificationManager

  private fun firePendingIntent(ctx: Context, title: String, body: String): PendingIntent {
    val intent = Intent(ctx, AlarmReceiver::class.java)
      .setAction(ACTION_FIRE)
      .putExtra(EXTRA_TITLE, title)
      .putExtra(EXTRA_BODY, body)
    return PendingIntent.getBroadcast(
      ctx,
      REQUEST_FIRE,
      intent,
      PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
    )
  }

  private fun launchAppPendingIntent(ctx: Context): PendingIntent? {
    val launch = ctx.packageManager.getLaunchIntentForPackage(ctx.packageName) ?: return null
    return PendingIntent.getActivity(ctx, REQUEST_SHOW, launch, PendingIntent.FLAG_IMMUTABLE)
  }

  fun canScheduleExact(ctx: Context): Boolean =
    Build.VERSION.SDK_INT < Build.VERSION_CODES.S || alarmManager(ctx).canScheduleExactAlarms()

  fun canUseFullScreenIntent(ctx: Context): Boolean =
    Build.VERSION.SDK_INT < Build.VERSION_CODES.UPSIDE_DOWN_CAKE ||
      notificationManager(ctx).canUseFullScreenIntent()

  fun schedule(ctx: Context, triggerAtMs: Long, title: String, body: String) {
    val am = alarmManager(ctx)
    val fire = firePendingIntent(ctx, title, body)
    val show = launchAppPendingIntent(ctx)
    if (canScheduleExact(ctx) && show != null) {
      am.setAlarmClock(AlarmManager.AlarmClockInfo(triggerAtMs, show), fire)
    } else {
      // Without exact-alarm access Android may delay this by a few minutes
      am.setAndAllowWhileIdle(AlarmManager.RTC_WAKEUP, triggerAtMs, fire)
    }
  }

  fun cancelScheduled(ctx: Context) {
    // PendingIntent equality ignores extras, so this matches whatever was scheduled
    val fire = firePendingIntent(ctx, "", "")
    alarmManager(ctx).cancel(fire)
    fire.cancel()
  }

  private fun ensureChannel(ctx: Context) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    val nm = notificationManager(ctx)
    if (nm.getNotificationChannel(CHANNEL_ID) != null) return
    val channel = NotificationChannel(CHANNEL_ID, "Alarm Timer", NotificationManager.IMPORTANCE_HIGH).apply {
      description = "Berdering seperti alarm saat sesi timer selesai"
      // Follows the user's alarm tone and alarm volume, not the notification volume
      setSound(
        Settings.System.DEFAULT_ALARM_ALERT_URI,
        AudioAttributes.Builder()
          .setUsage(AudioAttributes.USAGE_ALARM)
          .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
          .build()
      )
      enableVibration(true)
      vibrationPattern = VIBRATION
      setBypassDnd(true)
      lockscreenVisibility = Notification.VISIBILITY_PUBLIC
    }
    nm.createNotificationChannel(channel)
  }

  private fun smallIcon(ctx: Context): Int {
    // Monochrome icon generated by the expo-notifications config plugin
    val id = ctx.resources.getIdentifier("notification_icon", "drawable", ctx.packageName)
    return if (id != 0) id else ctx.applicationInfo.icon
  }

  fun alarmScreenIntent(ctx: Context, title: String, body: String): Intent =
    Intent(ctx, AlarmActivity::class.java)
      .putExtra(EXTRA_TITLE, title)
      .putExtra(EXTRA_BODY, body)
      .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_NO_USER_ACTION)

  fun ring(ctx: Context, title: String, body: String) {
    ensureChannel(ctx)
    val screen = PendingIntent.getActivity(
      ctx,
      REQUEST_SCREEN,
      alarmScreenIntent(ctx, title, body),
      PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
    )
    val dismiss = PendingIntent.getBroadcast(
      ctx,
      REQUEST_DISMISS,
      Intent(ctx, AlarmReceiver::class.java).setAction(ACTION_DISMISS),
      PendingIntent.FLAG_IMMUTABLE
    )
    val notification = NotificationCompat.Builder(ctx, CHANNEL_ID)
      .setSmallIcon(smallIcon(ctx))
      .setContentTitle(title)
      .setContentText(body)
      .setPriority(NotificationCompat.PRIORITY_MAX)
      .setCategory(NotificationCompat.CATEGORY_ALARM)
      .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
      .setFullScreenIntent(screen, true)
      .setContentIntent(screen)
      .setDeleteIntent(dismiss)
      .setOngoing(true)
      .setAutoCancel(false)
      .addAction(0, "Matikan", dismiss)
      // Pre-Android 8 has no channels: set sound/vibration on the notification itself
      .setSound(Settings.System.DEFAULT_ALARM_ALERT_URI, AudioManager.STREAM_ALARM)
      .setVibrate(VIBRATION)
      .setTimeoutAfter(RING_TIMEOUT_MS)
      .build()
    // Loop the sound and vibration until the notification is cancelled
    notification.flags = notification.flags or Notification.FLAG_INSISTENT
    notificationManager(ctx).notify(NOTIFICATION_ID, notification)
  }

  fun isRinging(ctx: Context): Boolean =
    notificationManager(ctx).activeNotifications.any { it.id == NOTIFICATION_ID }

  fun dismiss(ctx: Context) {
    notificationManager(ctx).cancel(NOTIFICATION_ID)
    dismissListeners.toList().forEach { it() }
  }
}
